#!/usr/bin/env python3
"""Validate UTF-8 CLI/GUI catalogs and regenerate their embedded tables.

Run after editing either locales directory; --check detects stale output.
Only named {placeholders} are supported, never printf format directives.
"""
import argparse
import ast
from html.parser import HTMLParser
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/linux/Translations.inc'


def load_catalogs(directory):
    catalogs = {}
    for path in sorted(directory.glob('*.json')):
        if not re.fullmatch(r'[a-z]{2,3}(?:_[A-Z]{2})?', path.stem):
            raise ValueError('Invalid locale name: ' + path.stem)
        def unique(pairs):
            result = {}
            for key, value in pairs:
                if key in result:
                    raise ValueError('Duplicate message: ' + key)
                result[key] = value
            return result
        catalog = json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=unique)
        if not isinstance(catalog, dict):
            raise ValueError('Catalog must be an object')
        for message, translation in catalog.items():
            if not message or '\0' in message or not isinstance(translation, str) or not translation or '\0' in translation:
                raise ValueError('Invalid translation: ' + message)
            def fields(text):
                names = re.findall(r'\{[a-z]+\}', text)
                if '{' in re.sub(r'\{[a-z]+\}', '', text) or '}' in re.sub(r'\{[a-z]+\}', '', text):
                    raise ValueError('Invalid placeholder: ' + text)
                return sorted(names)
            if fields(message) != fields(translation):
                raise ValueError('Placeholder mismatch: ' + message)
        catalogs[path.stem] = catalog
    english = catalogs.get('en')
    if not english or any(key != value for key, value in english.items()):
        raise ValueError('en.json must contain identity translations')
    for locale, catalog in catalogs.items():
        if catalog.keys() != english.keys():
            raise ValueError('Message set differs from English: ' + locale)
    return catalogs


def generate(directory):
    catalogs = load_catalogs(directory)
    lines = ['// Generated by tools/compile_translations.py; do not edit.',
             'struct Translation { const char * locale; const char * message; const char * text; };',
             'static const Translation translations[] = {']
    for locale, catalog in sorted(catalogs.items()):
        for key, value in sorted(catalog.items()):
            lines.append('    {%s, %s, %s},' % tuple(json.dumps(x, ensure_ascii=False) for x in (locale, key, value)))
    return '\n'.join(lines + ['};', ''])


GUI_PAGE = ROOT / 'source/gui/web/index.html'
GUI_DIRECTORY = ROOT / 'source/gui/locales'
BEGIN_GUI = '  /* BEGIN GENERATED GUI CATALOGS */'
END_GUI = '  /* END GENERATED GUI CATALOGS */'


def gui_page(catalogs, source):
    # A catalog is data inside an inline script. JSON quoting alone does not
    # prevent </script> from ending that script in the HTML parser.
    data = json.dumps(catalogs, ensure_ascii=True, sort_keys=True).replace('<', r'\u003c').replace('>', r'\u003e').replace('&', r'\u0026')
    if source.count(BEGIN_GUI) != 1 or source.count(END_GUI) != 1:
        raise ValueError('GUI catalog markers are missing or duplicated')
    before, rest = source.split(BEGIN_GUI)
    _, after = rest.split(END_GUI)
    return before + BEGIN_GUI + '\n  const GUI_CATALOGS = ' + data + ';\n' + END_GUI + after


class StaticMessages(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.excluded = []
        self.messages = set()

    def handle_starttag(self, tag, attrs):
        if tag in ('script', 'style', 'code', 'kbd'):
            self.excluded.append(tag)
        if not self.excluded:
            for key, value in attrs:
                if key in ('title', 'aria-label', 'placeholder') and value:
                    self.messages.add(value)

    def handle_endtag(self, tag):
        if self.excluded and tag == self.excluded[-1]:
            self.excluded.pop()

    def handle_data(self, text):
        if not self.excluded and re.search('[A-Za-z]', text):
            self.messages.add(text.strip())


def check_gui_coverage(catalogs, source):
    parser = StaticMessages()
    parser.feed(source)
    missing = parser.messages - catalogs['en'].keys()
    # Named t() calls are literal message keys; dynamic backend enum values
    # are intentionally separate from these source-owned UI messages.
    stripped = source.split(BEGIN_GUI)[0] + source.split(END_GUI)[1]
    for literal in re.findall(r"\bt\((\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*')", stripped):
        key = ast.literal_eval(literal)
        if key not in catalogs['en']:
            missing.add(key)
    for pair in re.findall(r"\btn\((\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*'),\s*(\"(?:\\.|[^\"\\])*\"|'(?:\\.|[^'\\])*')", stripped):
        for literal in pair:
            key = ast.literal_eval(literal)
            if key not in catalogs['en']:
                missing.add(key)
    if missing:
        raise ValueError('Uncatalogued GUI messages: ' + repr(sorted(missing)))


def check_cli_coverage(catalogs):
    missing = set()
    for path in (ROOT / 'source/linux').glob('*.cpp'):
        source = path.read_text(encoding='utf-8')
        translated = set()
        for literals in re.findall(r'\bTranslate\(\s*((?:"(?:\\.|[^"\\])*"\s*)+)', source):
            key = ''.join(ast.literal_eval(x) for x in re.findall(r'"(?:\\.|[^"\\])*"', literals))
            translated.add(key)
            if key not in catalogs['en']:
                missing.add(key)
        # A message that is printed from a plain literal never reaches the
        # catalog, so it stays English in every language.
        for message in output_messages(source):
            if message not in translated:
                missing.add(message)
        for message in operation_messages(source):
            if message not in catalogs['en']:
                missing.add(message)
    for message in command_help_messages():
        if message not in catalogs['en']:
            missing.add(message)
    if missing:
        raise ValueError('Uncatalogued CLI messages: ' + repr(sorted(missing)))


OUTPUT_CALL = re.compile(
    r'(?:Console::Instance\(\)|console)\.(?:Status|Error|WriteLine|LogEvent)\(\s*"')


def output_messages(source):
    """The messages a console call prints from a plain string literal.

    A message that reaches the user without going through the catalog is
    the one that stays English in every language, so the check that the
    catalog is complete has to see it as well. A literal without a letter
    is only layout, and the 'LSCP-' banners belong to the protocol the
    graphical client speaks, not to the language of the client.
    """
    messages = set()
    for match in OUTPUT_CALL.finditer(source):
        start = match.end() - 1
        index = match.end()
        parts = []
        while True:
            while True:
                if source[index] == '\\':
                    index += 2
                    continue
                if source[index] == '"':
                    break
                index += 1
            parts.append(ast.literal_eval(source[start:index + 1]))
            index += 1
            # Adjacent literals are one message.
            probe = index
            while probe < len(source) and source[probe].isspace():
                probe += 1
            if probe < len(source) and source[probe] == '"':
                start = probe
                index = probe + 1
                continue
            break
        message = ''.join(parts)
        if not re.search('[A-Za-z]', message):
            continue
        if message.startswith('LSCP-'):
            continue
        messages.add(message)
    return messages


OPERATION_CALL = re.compile(r'Texts::(?:RemoteError|LocalError)\(\s*"')


def operation_messages(source):
    """The operations the error helpers name.

    The helper looks the operation up in the catalog by itself, so an
    operation that is not there stays English inside a translated
    sentence.
    """
    messages = set()
    for match in OPERATION_CALL.finditer(source):
        index = match.end()
        start = index - 1
        while True:
            if source[index] == '\\':
                index += 2
                continue
            if source[index] == '"':
                break
            index += 1
        messages.add(ast.literal_eval(source[start:index + 1]))
    return messages


HELP_TABLE = re.compile(r'kScriptCommandHelps\[\] = \{(.*?)\n\};', re.S)
C_LITERAL = re.compile(r'"((?:[^"\\]|\\.)*)"')


def unescape_c(text):
    """The characters a C string literal stands for."""
    out = []
    index = 0
    simple = {'n': '\n', 't': '\t', 'r': '\r', '\\': '\\', '"': '"', "'": "'"}
    while index < len(text):
        char = text[index]
        if char == '\\' and index + 1 < len(text):
            following = text[index + 1]
            if following in simple:
                out.append(simple[following])
                index += 2
                continue
            if following == 'x' and index + 3 < len(text):
                out.append(chr(int(text[index + 2:index + 4], 16)))
                index += 4
                continue
        out.append(char)
        index += 1
    return ''.join(out)


def command_help_messages():
    """The per-command help texts of the script engine.

    They are data rather than calls, so the coverage check above cannot
    see them: a new help text that nobody translated would be the one
    message the client still answers in English. The table is read the
    way the compiler reads it - the literals of an entry joined together,
    with the C escapes resolved.
    """
    source = (ROOT / 'source/linux/Script.cpp').read_text(encoding='utf-8')
    block = HELP_TABLE.search(source)
    if not block:
        raise ValueError('No kScriptCommandHelps table in source/linux/Script.cpp')
    body = block.group(1)
    starts = [match.start() for match in re.finditer(r'\{\s*"', body)]
    messages = set()
    for index, start in enumerate(starts):
        end = starts[index + 1] if index + 1 < len(starts) else len(body)
        entry = body[start:end]
        name = re.match(r'\{\s*"((?:[^"\\]|\\.)*)"', entry)
        if not name:
            raise ValueError('A help entry has no command name')
        literals = C_LITERAL.findall(entry[name.end():])
        messages.add(unescape_c(''.join(literals)))
    return messages


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    catalogs = load_catalogs(GUI_DIRECTORY)
    page = GUI_PAGE.read_text(encoding='utf-8')
    check_gui_coverage(catalogs, page)
    check_cli_coverage(load_catalogs(ROOT / 'source/linux/locales'))
    outputs = {OUTPUT: generate(ROOT / 'source/linux/locales'),
               GUI_PAGE: gui_page(catalogs, page)}
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                parser.exit(1, 'Translation output is stale; run tools/compile_translations.py\n')
        else:
            path.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    main()
